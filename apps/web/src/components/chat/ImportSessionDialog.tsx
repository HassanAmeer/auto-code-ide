import { useState, useRef } from "react";
import { UploadIcon, FileJsonIcon, CheckCircle2Icon, AlertCircleIcon } from "lucide-react";
import {
  Dialog,
  DialogPopup,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogPanel,
  DialogFooter,
} from "../ui/dialog";
import { Button } from "../ui/button";
import { toastManager } from "../ui/toast";
import { parseImportedSession, type ExportedSession } from "~/lib/sessionExportImport";
import { useImportSessionStore } from "./importSessionStore";

export interface ImportSessionDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onImportSession: (session: ExportedSession) => void;
}

export function ImportSessionDialogHost() {
  const { isOpen, closeDialog } = useImportSessionStore();

  const handleImport = (session: ExportedSession) => {
    toastManager.add({
      type: "success",
      title: "Session restored successfully",
      description: `Imported "${session.thread.title}" (${session.messages.length} messages).`,
    });
  };

  return (
    <ImportSessionDialog
      open={isOpen}
      onOpenChange={(open) => {
        if (!open) closeDialog();
      }}
      onImportSession={handleImport}
    />
  );
}

export function ImportSessionDialog({
  open,
  onOpenChange,
  onImportSession,
}: ImportSessionDialogProps) {
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [parsedSession, setParsedSession] = useState<ExportedSession | null>(null);
  const [error, setError] = useState<string | null>(null);

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    setSelectedFile(file);
    setError(null);

    const reader = new FileReader();
    reader.onload = (event) => {
      const content = event.target?.result as string;
      const res = parseImportedSession(content);
      if (res.success && res.data) {
        setParsedSession(res.data);
      } else {
        setParsedSession(null);
        setError(res.error || "Failed to parse session file.");
      }
    };
    reader.onerror = () => {
      setError("Failed to read file.");
    };
    reader.readAsText(file);
  };

  const handleConfirmImport = () => {
    if (!parsedSession) return;
    onImportSession(parsedSession);
    onOpenChange(false);
    setSelectedFile(null);
    setParsedSession(null);
    setError(null);
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogPopup className="sm:max-w-md">
        <DialogHeader>
          <div className="flex items-center gap-2">
            <FileJsonIcon className="size-5 text-primary" />
            <DialogTitle>Import Chat Session</DialogTitle>
          </div>
          <DialogDescription>
            Restore a previously exported chat session JSON file to view or continue the
            conversation.
          </DialogDescription>
        </DialogHeader>

        <DialogPanel className="space-y-4 py-2">
          <input
            ref={fileInputRef}
            type="file"
            accept=".json,application/json"
            onChange={handleFileChange}
            className="hidden"
          />

          <div
            onClick={() => fileInputRef.current?.click()}
            className="flex flex-col items-center justify-center p-6 border-2 border-dashed border-border/80 hover:border-primary/60 rounded-xl bg-muted/20 cursor-pointer transition-colors text-center"
          >
            <UploadIcon className="size-8 text-muted-foreground mb-2" />
            <p className="text-sm font-medium text-foreground">
              {selectedFile ? selectedFile.name : "Click to select session JSON file"}
            </p>
            <p className="text-xs text-muted-foreground mt-1">
              Supports .json files generated by AutoCode IDE / OpenCode
            </p>
          </div>

          {error && (
            <div className="flex items-center gap-2 rounded-lg border border-destructive/30 bg-destructive/10 p-3 text-xs text-destructive">
              <AlertCircleIcon className="size-4 shrink-0" />
              <span>{error}</span>
            </div>
          )}

          {parsedSession && (
            <div className="rounded-lg border border-border/70 bg-card p-3 space-y-1.5 text-xs">
              <div className="flex items-center justify-between font-semibold text-foreground">
                <span className="truncate">{parsedSession.thread.title}</span>
                <span className="flex items-center gap-1 text-emerald-500 text-[11px]">
                  <CheckCircle2Icon className="size-3.5" /> Valid
                </span>
              </div>
              <div className="text-muted-foreground flex items-center justify-between text-[11px]">
                <span>Messages: {parsedSession.messages.length}</span>
                <span>Exported: {new Date(parsedSession.exportedAt).toLocaleDateString()}</span>
              </div>
            </div>
          )}
        </DialogPanel>

        <DialogFooter className="gap-2 sm:gap-0">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={() => {
              onOpenChange(false);
              setSelectedFile(null);
              setParsedSession(null);
              setError(null);
            }}
          >
            Cancel
          </Button>
          <Button type="button" size="sm" disabled={!parsedSession} onClick={handleConfirmImport}>
            Restore Session
          </Button>
        </DialogFooter>
      </DialogPopup>
    </Dialog>
  );
}
